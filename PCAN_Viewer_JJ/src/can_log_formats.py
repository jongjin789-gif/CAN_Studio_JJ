"""CAN log file formats shared by Record, the log viewer and trigger capture.

* TRC 2.1 (PEAK): this app's native format; header/line layout used by Record.
* Vector ASC / BLF: read and written through python-can (no extra package).

Log entries are plain dicts, the same shape LogParserThread produces:
``timestamp, offset_ms, type, bus, can_id, dlc, data, is_extended_id`` and optionally
``direction`` ('Rx'/'Tx'), ``format`` and ``source_line``.
Bus numbers are 1-based; python-can/Vector channels are 0-based (channel = bus - 1).
"""
import datetime
import os
import tempfile

import can

VECTOR_EXTENSIONS = ('.asc', '.blf')
FD_TYPES = ('FD', 'FB', 'FE', 'FBE')
BRS_TYPES = ('FB', 'FBE')
_OLE_EPOCH = datetime.datetime(1899, 12, 30)


def log_format(path):
    ext = os.path.splitext(path)[1].lower()
    return ext[1:] if ext in VECTOR_EXTENSIONS else 'trc'


def is_vector_log(path):
    return log_format(path) in ('asc', 'blf')


# --------------------------------------------------------------------------- TRC
def trc_header(start_dt, bitrates, notes=()):
    """TRC 2.1 header. ``start_dt`` must be the time of offset 0 (first frame).

    ``notes`` are extra comment lines (e.g. the Record ID filter); readers skip them.
    """
    ole_date = (start_dt - _OLE_EPOCH).total_seconds() / 86400.0
    header = [
        ";$FILEVERSION=2.1",
        f";$STARTTIME={ole_date:.13f}",
        ";$COLUMNS=N,O,T,B,I,d,R,L,D",
        ";",
        f";   Start time: {start_dt.strftime('%Y-%m-%d %H:%M:%S.%f')[:-3]}",
        ";   Generated by CAN Studio JJ",
    ]
    header.extend(f";   {note}" for note in notes)
    header.extend([
        ";-------------------------------------------------------------------------------",
        ";   Bus  Connection   Net Connection     Protocol  Bit rate",
    ])
    for b, br in bitrates.items():
        header.append(f";   {b}    Connection{b}  CAN_Monitor        CAN       {br}")
    header.extend([
        ";-------------------------------------------------------------------------------",
        ";   Message    Time    Type    ID     Rx/Tx",
        ";   Number     Offset  |  Bus  [hex]  |  Reserved",
        ";   |          [ms]    |  |    |      |  |  Data Length Code",
        ";   |          |       |  |    |      |  |  |    Data [hex] ...",
        ";   |          |       |  |    |      |  |  |    |",
        ";---+--- ------+------ +- +- --+----- +- +- +--- +- -- -- -- -- -- -- --"
    ])
    return header


def trc_line(number, offset_ms, can_id, data, is_ext, is_fd, is_rx, bus_num):
    can_id_hex = f"{can_id:08X}" if is_ext else f"{can_id:04X}"
    data_hex = " ".join(f"{b:02X}" for b in data)
    msg_type = "FD" if is_fd else "DT"
    direction = "Rx" if is_rx else "Tx"
    return (f"{number:>8} {offset_ms:>13.3f} {msg_type} {bus_num} {can_id_hex:>9} "
            f"{direction} - {len(data):>2}    {data_hex}")


def parse_app_trc_line(line, start_timestamp):
    """Parse a body line written by :func:`trc_line` back into a log entry."""
    tokens = line.split()
    if len(tokens) < 8 or tokens[6] != '-':
        return None
    offset_ms = float(tokens[1])
    length = int(tokens[7])
    data = bytes.fromhex(''.join(tokens[8:8 + length]))
    if len(data) != length:
        return None
    return dict(timestamp=start_timestamp + offset_ms / 1000.0, offset_ms=offset_ms,
                type=tokens[2], bus=int(tokens[3]), can_id=int(tokens[4], 16), dlc=length,
                data=data, is_extended_id=len(tokens[4]) > 4, direction=tokens[5])


def write_trc_frames(path, frames, bitrates):
    """Write ``frames`` = [(ts, bus, can_id, data, is_ext, is_fd, is_rx), ...] as TRC."""
    frames = sorted(frames, key=lambda frame: frame[0])
    start = frames[0][0] if frames else datetime.datetime.now().timestamp()
    lines = trc_header(datetime.datetime.fromtimestamp(start), bitrates)
    for number, (ts, bus, can_id, data, is_ext, is_fd, is_rx) in enumerate(frames, 1):
        lines.append(trc_line(number, max(0.0, (ts - start) * 1000.0), can_id, data,
                              is_ext, is_fd, is_rx, bus))
    _atomic_text(path, "\n".join(lines) + "\n")
    return len(frames)


def _atomic_text(path, text):
    path = os.path.abspath(path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, pending = tempfile.mkstemp(prefix='.log-', dir=os.path.dirname(path))
    try:
        with os.fdopen(fd, 'w', encoding='utf-8', newline='\n') as out:
            out.write(text)
            out.flush()
            os.fsync(out.fileno())
        os.replace(pending, path)
    finally:
        if os.path.exists(pending):
            os.remove(pending)


# ------------------------------------------------------------------ Vector ASC/BLF
def _reader(path, absolute=True):
    if log_format(path) == 'asc':
        # Absolute timestamps keep the same time axis as TRC logs.
        return can.ASCReader(path, relative_timestamp=not absolute)
    return can.BLFReader(path)


def read_vector_entries(path, cancelled=lambda: False):
    """Read data frames from an ASC/BLF file. Error and remote frames are skipped."""
    try:
        return _read_vector_entries(path, cancelled, absolute=True)
    except (OSError, ValueError, OverflowError):
        if log_format(path) != 'asc':
            raise
        # An ASC start date the OS cannot convert (e.g. 1970 on Windows):
        # use relative times based on the file's modification time.
        return _read_vector_entries(path, cancelled, absolute=False, base=os.path.getmtime(path))


def _read_vector_entries(path, cancelled, absolute=True, base=0.0):
    entries = []
    start = None
    fmt = log_format(path)
    reader = _reader(path, absolute)
    try:
        for index, msg in enumerate(reader):
            if index % 2000 == 0 and cancelled():
                return None
            if msg.is_error_frame or msg.is_remote_frame:
                continue
            if start is None:
                start = msg.timestamp
            channel = msg.channel if isinstance(msg.channel, int) else 0
            is_fd = bool(msg.is_fd)
            entries.append(dict(
                timestamp=float(msg.timestamp) + base, offset_ms=max(0.0, (msg.timestamp - start) * 1000.0),
                type=('FB' if msg.bitrate_switch else 'FD') if is_fd else 'DT',
                bus=channel + 1, can_id=int(msg.arbitration_id), dlc=len(msg.data),
                data=bytes(msg.data), is_extended_id=bool(msg.is_extended_id),
                direction='Rx' if msg.is_rx else 'Tx', format=fmt, source_line=index + 1))
    finally:
        stop = getattr(reader, 'stop', None)
        if callable(stop):
            stop()
    return entries


def entry_message(entry):
    msg_type = entry.get('type', 'DT')
    return can.Message(
        timestamp=float(entry['timestamp']), arbitration_id=int(entry['can_id']),
        is_extended_id=bool(entry.get('is_extended_id', entry['can_id'] > 0x7FF)),
        data=bytes(entry['data']), is_fd=msg_type in FD_TYPES,
        bitrate_switch=msg_type in BRS_TYPES, channel=int(entry.get('bus', 1)) - 1,
        is_rx=entry.get('direction', 'Rx') != 'Tx')


def write_vector_log(path, entries):
    """Write log entries as ASC or BLF (chosen by the file extension)."""
    path = os.path.abspath(path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    ext = os.path.splitext(path)[1].lower()
    fd, pending = tempfile.mkstemp(prefix='.log-', suffix=ext, dir=os.path.dirname(path))
    os.close(fd)
    count = 0
    try:
        writer = can.ASCWriter(pending) if ext == '.asc' else can.BLFWriter(pending)
        try:
            for entry in entries:
                writer.on_message_received(entry_message(entry))
                count += 1
        finally:
            writer.stop()
        os.replace(pending, path)
    finally:
        if os.path.exists(pending):
            os.remove(pending)
    return count


def convert_app_trc(source_path, start_timestamp, dest_path):
    """Convert this app's TRC body lines (Record temp file) into an ASC/BLF file."""
    def entries():
        with open(source_path, 'r', encoding='utf-8') as stream:
            for line in stream:
                entry = parse_app_trc_line(line, start_timestamp)
                if entry is not None:
                    yield entry
    return write_vector_log(dest_path, entries())
